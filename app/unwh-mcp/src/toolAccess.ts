export type HiddenTool = { name: string; scope: string };

export function toolsHiddenForScopes(names: readonly string[], scopes: readonly string[]): HiddenTool[] {
  return names.flatMap((name) => {
    const scope = TOOL_SCOPES[name];
    if (!scope || scopeAllows(scopes, scope)) return [];
    return [{ name, scope }];
  });
}

/** Tools only staff or admins should see. Hidden from tools/list for callers whose token user is not staff, whatever their scopes; the API still enforces staff checks. The published catalog (unw_get_catalog) is not in this list: GET /api/v1/catalog is public and Try me reads it with a client token. */
