export function toolsHiddenForClients(names: readonly string[]): HiddenTool[] {
  const staffOnly = new Set(STAFF_ONLY_TOOLS);
  return names.filter((name) => staffOnly.has(name)).map((name) => ({ name, scope: "staff" }));
}
