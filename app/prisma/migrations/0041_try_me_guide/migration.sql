-- Try me help guide: hands-on exercises a visitor runs with their own agent against the sandbox MCP token.
-- Each exercise lists the MCP tools it uses; tests/api/tryMeGuide.test.ts fails if they cover under 80% of the tools a client token can see.
CREATE TABLE "try_me_exercise" (
  "code" TEXT NOT NULL,
  "sort" INTEGER NOT NULL DEFAULT 0,
  "title" TEXT NOT NULL,
  "goal" TEXT NOT NULL,
  "prompt" TEXT NOT NULL,
  "active" BOOLEAN NOT NULL DEFAULT true,
  CONSTRAINT "try_me_exercise_pkey" PRIMARY KEY ("code")
);

CREATE TABLE "try_me_exercise_tool" (
  "exercise_code" TEXT NOT NULL,
  "tool_name" TEXT NOT NULL,
  CONSTRAINT "try_me_exercise_tool_pkey" PRIMARY KEY ("exercise_code", "tool_name"),
  CONSTRAINT "try_me_exercise_tool_exercise_code_fkey" FOREIGN KEY ("exercise_code") REFERENCES "try_me_exercise"("code") ON DELETE CASCADE ON UPDATE CASCADE
);

